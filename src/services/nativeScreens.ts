/**
 * Οθόνες του iOS που ανοίγει η εφαρμογή πάνω από τη σελίδα: προβολή αρχείου (QuickLook), σαρωτής εγγράφων, σάρωση QR.
 * Όσο είναι ανοιχτές, η σελίδα είναι «κρυμμένη» αλλά ο χρήστης είναι ΜΕΣΑ στην εφαρμογή — γι' αυτό το κλείδωμα
 * (data/appLock) δεν κοιτά την ορατότητα της σελίδας, μόνο την πραγματική έξοδο στο παρασκήνιο («pause» του iOS).
 * Όταν είναι ενεργό το κλείδωμα, οι οθόνες αυτές κλείνουν στο παρασκήνιο, ώστε να μη μένουν πάνω από την οθόνη
 * κλειδώματος. Το αν είναι ενεργό το δηλώνει το data/appLock εδώ (οι υπηρεσίες δεν εξαρτώνται από τα δεδομένα).
 */
let closeOnBackground: () => boolean = () => false;

export function setCloseOnBackground(fn: () => boolean): void { closeOnBackground = fn; }
/** true: η οθόνη που ανοίγει τώρα πρέπει να κλείσει μόλις η εφαρμογή πάει στο παρασκήνιο */
export const closeScreensOnBackground = (): boolean => closeOnBackground();
